#!/usr/bin/env python3
"""The app's screen text and the server's dictionary (i18n/client/ there).

The server's dictionary is the source of the text; the tables in source/i18n/
are generated from it at a pinned tag, so a client build never follows the
server's main branch by itself.

  i18n.py extract OUT_DIR          the tables as dictionary files: OUT_DIR/<code>.json
                                   (one flat object per language) and languages.json
  i18n.py generate --repo PATH     the tables from the server repository at the tag
                                   in source/i18n/DICTIONARY
  i18n.py generate --dir DIR       the same from plain dictionary files
  i18n.py selftest                 extract, generate back and compare; check every
                                   shipped language with build-host/strings-check
"""
import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "source" / "i18n"
PIN = TABLES / "DICTIONARY"
CHECK = ROOT / "build-host" / "strings-check"
# The shipped languages besides English: code, the Language enumerator, and
# the name the file's first line gives it.
SHIPPED = [
    ("ko", "Korean", "Korean"),
    ("ja", "Japanese", "Japanese"),
    ("zh", "Chinese", "Chinese"),
    ("zh-Hant", "ChineseTraditional", "Traditional Chinese"),
    ("es", "Spanish", "Spanish"),
    ("fr", "French", "French"),
    ("de", "German", "German"),
    ("it", "Italian", "Italian"),
    ("pt", "Portuguese", "Portuguese"),
    ("nl", "Dutch", "Dutch"),
    ("ru", "Russian", "Russian"),
]
ROW = re.compile(r'^\s*\{"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\},\s*$')


def unescape(text):
    return re.sub(r'\\(.)', lambda m: "\n" if m.group(1) == "n" else "\t" if m.group(1) == "t" else m.group(1), text)


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def read_table(path):
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = ROW.match(line)
        if not match:
            continue
        key = unescape(match.group(1))
        if key in rows:
            sys.exit(f"{path}: {key!r} twice")
        rows[key] = unescape(match.group(2))
    return rows


def write_table(path, enumerator, name, rows, origin):
    lines = [
        f"// {name} screen text, keyed by the English text (core/I18n.hpp).",
        f"// Generated by scripts/i18n.py from {origin}: change the dictionary, not this file.",
        '#include "core/I18n.hpp"',
        "namespace foil {",
        "namespace {",
        "const Translation rows[] = {",
    ]
    lines += [f'    {{"{escape(key)}", "{escape(text)}"}},' for key, text in rows.items()]
    lines += [
        "};",
        f"const TranslationTable table(Language::{enumerator}, rows, sizeof rows / sizeof rows[0]);",
        "} // namespace",
        "} // namespace foil",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def languages():
    if not CHECK.exists():
        sys.exit(f"{CHECK} is missing: run make build-host/strings-check")
    return json.loads(subprocess.run([str(CHECK), "languages"], check=True, capture_output=True, text=True).stdout)


def extract(out):
    out.mkdir(parents=True, exist_ok=True)
    for code, _, _ in SHIPPED:
        rows = read_table(TABLES / f"lang_{code}.cpp")
        (out / f"{code}.json").write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "languages.json").write_text(json.dumps(languages(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def pinned_tag():
    if not PIN.exists():
        return None
    match = re.search(r"^tag\s*=\s*(\S+)", PIN.read_text(encoding="utf-8"), re.M)
    return match.group(1) if match else None


def dictionary(code, repo, tag, folder):
    if folder:
        path = folder / f"{code}.json"
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
    shown = subprocess.run(["git", "-C", str(repo), "show", f"{tag}:i18n/client/{code}.json"],
                           capture_output=True, text=True, encoding="utf-8")
    return json.loads(shown.stdout) if shown.returncode == 0 else None


def generate(repo, tag, folder, out, origin):
    # A shipped language the dictionary lacks, or a key one language has and
    # another does not, stops here: the tables stay complete.
    loaded = {}
    for code, _, _ in SHIPPED:
        rows = dictionary(code, repo, tag, folder)
        if rows is None:
            sys.exit(f"the dictionary has no {code}.json")
        loaded[code] = rows
    keys = set(loaded[SHIPPED[0][0]])
    for code, rows in loaded.items():
        if set(rows) != keys:
            missing, extra = sorted(keys - set(rows)), sorted(set(rows) - keys)
            sys.exit(f"{code}.json: {len(missing)} keys missing, {len(extra)} extra; first: {(missing or extra)[0]!r}")
    out.mkdir(parents=True, exist_ok=True)
    for code, enumerator, name in SHIPPED:
        write_table(out / f"lang_{code}.cpp", enumerator, name, loaded[code], origin)


def selftest():
    with tempfile.TemporaryDirectory() as temp:
        folder, back = Path(temp) / "dict", Path(temp) / "back"
        extract(folder)
        generate(None, None, folder, back, "the selftest")
        failed = False
        for code, _, _ in SHIPPED:
            if read_table(back / f"lang_{code}.cpp") != read_table(TABLES / f"lang_{code}.cpp"):
                print(f"{code}: the table does not come back the same", file=sys.stderr)
                failed = True
            report = subprocess.run([str(CHECK), "check", str(folder / f"{code}.json")],
                                    capture_output=True, text=True, cwd=ROOT)
            if report.returncode != 0:
                print(f"{code}: strings-check refused it\n{report.stdout}{report.stderr}", file=sys.stderr)
                failed = True
        if failed:
            sys.exit(1)
    print(f"i18n tools: {len(SHIPPED)} languages round-trip and pass strings-check")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("extract").add_argument("out", type=Path)
    gen = commands.add_parser("generate")
    source = gen.add_mutually_exclusive_group(required=True)
    source.add_argument("--repo", type=Path, help="a clone of the server repository")
    source.add_argument("--dir", type=Path, help="dictionary files instead of the repository")
    commands.add_parser("selftest")
    args = parser.parse_args()
    if args.command == "extract":
        extract(args.out)
    elif args.command == "selftest":
        selftest()
    elif args.dir:
        generate(None, None, args.dir, TABLES, f"dictionary files in {args.dir.name}/")
    else:
        tag = pinned_tag()
        if not tag:
            sys.exit(f"{PIN} names no tag (tag = <server tag>)")
        generate(args.repo, tag, None, TABLES, f"the server dictionary at tag {tag}")


if __name__ == "__main__":
    main()
